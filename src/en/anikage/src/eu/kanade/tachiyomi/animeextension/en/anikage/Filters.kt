object Filters {

    open class QueryPartFilter(
        displayName: String,
        val vals: Array<Pair<String, String>>,
    ) : AnimeFilter.Select<String>(
        displayName,
        vals.map { it.first }.toTypedArray(),
    ) {
        fun toQueryPart() = vals[state].second
    }

    open class CheckBoxFilterList(name: String, values: List<CheckBox>) : AnimeFilter.Group<AnimeFilter.CheckBox>(name, values)

    private class CheckBoxVal(name: String, state: Boolean = false) : AnimeFilter.CheckBox(name, state)

    private inline fun <reified R> AnimeFilterList.asQueryPart(): String = (this.getFirst<R>() as QueryPartFilter).toQueryPart()

    private inline fun <reified R> AnimeFilterList.getFirst(): R = this.filterIsInstance<R>().first()

    class OriginFilter : QueryPartFilter("Origin", AnikageFiltersData.ORIGIN)
    class SeasonFilter : QueryPartFilter("Season", AnikageFiltersData.SEASONS)
    class ReleaseYearFilter : QueryPartFilter("Released at", AnikageFiltersData.YEARS)
    class SortByFilter : QueryPartFilter("Sort By", AnikageFiltersData.SORT_BY)
    class FormatFilter : QueryPartFilter("Format", AnikageFiltersData.FORMATS)
    class StatusFilter : QueryPartFilter("Status", AnikageFiltersData.STATUS)
    class SourceFilter : QueryPartFilter("Source", AnikageFiltersData.SOURCES)
    class ScoreFilter : QueryPartFilter("Score", AnikageFiltersData.SCORES)
    class EpisodesFilter : QueryPartFilter("Episodes", AnikageFiltersData.EPISODES)
    class AudioFilter : QueryPartFilter("Audio", AnikageFiltersData.AUDIOS)

    class GenresFilter :
        CheckBoxFilterList(
            "Genres",
            AnikageFiltersData.GENRES.map { CheckBoxVal(it.first, false) },
        )

    class TagsFilter :
        CheckBoxFilterList(
            "Tags",
            AnikageFiltersData.TAGS.map { CheckBoxVal(it.first, false) },
        )

    inline fun <reified T : CheckBoxFilterList> AnimeFilterList.parseCheckbox(
        options: Array<Pair<String, String>>,
    ): List<String> = (firstOrNull { it is T } as? T)
        ?.state
        ?.mapIndexedNotNull { index, checked ->
            if (checked.state) options[index].second else null
        }
        ?: emptyList()

    val FILTER_LIST get() = AnimeFilterList(
        SortByFilter(),
        AnimeFilter.Separator(),
        GenresFilter(),
        TagsFilter(),
        AnimeFilter.Separator(),
        FormatFilter(),
        StatusFilter(),
        SeasonFilter(),
        ReleaseYearFilter(),
        OriginFilter(),
        SourceFilter(),
        ScoreFilter(),
        EpisodesFilter(),
        AudioFilter(),
    )

    data class FilterSearchParams(
        val origin: String = "ALL",
        val season: String = "ALL",
        val releaseYear: String = "ALL",
        val sortBy: String = "TRENDING_DESC",
        val format: String = "ALL",
        val status: String = "ALL",
        val genres: List<String> = emptyList(),
        val tags: List<String> = emptyList(),
        val source: String = "ALL",
        val scoreMin: String = "ALL",
        val episodes: String = "ALL",
        val audio: String = "ALL",
    )

    internal fun getSearchParameters(filters: AnimeFilterList): FilterSearchParams {
        if (filters.isEmpty()) return FilterSearchParams()
        return FilterSearchParams(
            origin = filters.asQueryPart<OriginFilter>(),
            season = filters.asQueryPart<SeasonFilter>(),
            releaseYear = filters.asQueryPart<ReleaseYearFilter>(),
            sortBy = filters.asQueryPart<SortByFilter>(),
            format = filters.asQueryPart<FormatFilter>(),
            status = filters.asQueryPart<StatusFilter>(),
            source = filters.asQueryPart<SourceFilter>(),
            scoreMin = filters.asQueryPart<ScoreFilter>(),
            episodes = filters.asQueryPart<EpisodesFilter>(),
            audio = filters.asQueryPart<AudioFilter>(),
            genres = filters.parseCheckbox<GenresFilter>(AnikageFiltersData.GENRES),
            tags = filters.parseCheckbox<TagsFilter>(AnikageFiltersData.TAGS),
        )
    }

